import assert from 'node:assert/strict';
import {setupCommand,establishInstallingOwner} from './installation-fixture.mjs';
import {admitCapability} from './capability.mjs';

// Real signed Worker endpoint, retained request/delivery/access/budget owners and
// D1 projection. GitHub is octoemu; nothing supplies replacement receipts.
export async function reissue({ingress,github,http,db,id,creation,eventually}) {
  for(const user of [7,91]) await db.prepare("INSERT INTO users(user_id,login,avatar_url,last_seen_at) VALUES (?, ?, NULL, '2026-01-01T00:00:00Z')").bind(user,`user-${user}`).run();
  await http(`${ingress}/Installation/repo:1/onboard`,setupCommand({installation_id:1,account_id:100,account_login:'acme',account_type:'Organization',selected_repos:'all',installed_at:'2026-01-01T00:00:00Z'}));
  await establishInstallingOwner({http,ingress});
  const create=creation();
  assert.ok((await http(`${ingress}/InvitationLink/${create.link_id}/create`,create)).Ok);
  const removal=await fetch(`${ingress}/InvitationLink/${create.link_id}/prepare_access_removal`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({link_id:create.link_id,admin:create.admin,operation_id:id()})});
  assert.equal(removal.status,503,'reissue dependencies do not activate manual access removal');
  const admit={...admitCapability(create.link_id),link_id:create.link_id,requester_id:91,operation_id:id()};
  const admission=await http(`${ingress}/InvitationLink/${create.link_id}/admit`,admit);
  assert.equal(admission.result.kind,'accepted');
  const request=admission.result.request_id;
  const query={link_id:create.link_id,request_id:request,requester_id:91};
  const req=(method,input)=>http(`${ingress}/InvitationRequest/${request}/${method}`,input);
  const delivery=(generation,method,input)=>http(`${ingress}/RepositoryDelivery/${request}:10:${generation}/${method}`,input);
  const approval={link_id:create.link_id,request_id:request,operation_id:id(),admin:create.admin,action:{kind:'approve'}};
  const approved=await req('decide',approval);
  assert.equal(approved.outcome,'applied');
  const first=await eventually(()=>delivery(1,'status'),s=>s?.create.outcome.kind==='created');
  const originalRequest=await req('request_status',query);
  const observed_at=new Date().toISOString();
  await delivery(1,'reconcile',{delivery_key:`${request}:10:1`,expected_revision:first.revision,at:observed_at,evidence:{kind:'listed',upstream_id:first.create.outcome.upstream_id,expired:true}});
  const expired=await eventually(()=>delivery(1,'status'),s=>s?.settlement?.state==='expired');
  await eventually(()=>req('request_status',query),s=>s.state==='lapsed');
  await new Promise(resolve=>setTimeout(resolve,1100));
  const input={operation_id:id(),request_id:request,admin:create.admin,target:{kind:'repository',repo_id:10}};
  const result=await req('reissue',input);
  assert.deepEqual(result,{Ok:{delivery_generation:2}});
  assert.deepEqual(await req('reissue',input),result);
  const changed=await fetch(`${ingress}/InvitationRequest/${request}/reissue`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({...input,target:{kind:'repository',repo_id:999}})});
  assert.equal(changed.status,409);
  const second=await eventually(()=>delivery(2,'status'),s=>s?.create.outcome.kind==='created');
  assert.equal(second.create.command.delivery_generation,2);
  assert.equal(second.create.command.budget_attribution,'administrator_reissue');
  assert.equal(second.create.command.link_id,create.link_id);
  assert.equal(second.create.command.approval_id,first.create.command.approval_id);
  const canonicalKey=command=>`${command.request_id}:${command.repo_id}:${command.delivery_generation}`;
  assert.equal(canonicalKey(first.create.command),`${request}:10:1`);
  assert.equal(canonicalKey(second.create.command),`${request}:10:2`);
  assert.notEqual(canonicalKey(second.create.command),canonicalKey(first.create.command));
  assert.equal(Object.hasOwn(first.create.command,'invitation_id'),false);
  assert.equal(Object.hasOwn(second.create.command,'invitation_id'),false);
  assert.deepEqual(await delivery(1,'status'),expired,'historical generation keeps its original settlement');
  assert.deepEqual(await req('decide',approval),approved);
  assert.deepEqual(await http(`${ingress}/InvitationLink/${create.link_id}/admit`,admit),admission);
  const current=await req('request_status',query);
  assert.equal(current.state,'approved');
  assert.deepEqual(current.decision,originalRequest.decision);
  assert.equal(current.admitted_at,originalRequest.admitted_at);
  const progress=await req('delivery_progress',query);
  assert.equal(progress[0].delivery_generation,2);
  const proof=await eventually(()=>db.prepare('SELECT content FROM request_reissues WHERE request_id=? AND operation_id=?').bind(request,input.operation_id).first(),Boolean);
  assert.equal(JSON.parse(proof.content).delivery.after.delivery_generation,2);
  const projected=await eventually(()=>db.prepare('SELECT state,projection_revision FROM invitation_requests WHERE id=?').bind(request).first(),r=>r?.state==='approved'&&r.projection_revision===current.revision);
  assert.equal(projected.state,'approved');
  const events=await eventually(()=>db.prepare("SELECT id,occurred_at,metadata FROM audit_events WHERE event_type='delivery.reissued' AND target_id=?").bind(request).all(),r=>r.results.length===1);
  assert.deepEqual(await req('reissue',input),result);
  assert.deepEqual((await db.prepare("SELECT id,occurred_at,metadata FROM audit_events WHERE event_type='delivery.reissued' AND target_id=?").bind(request).all()).results,events.results);
  assert.equal((await github.requests('PUT')).length,2);
  assert.equal((await github.requests('DELETE')).length,1);
  const link=await http(`${ingress}/InvitationLink/${create.link_id}/link_status`,{link_id:create.link_id,admin:create.admin});
  assert.equal(link.uses,1,'administrator reissue consumes no additional link use');
  console.log('Signed Worker reissue: generation2, exact replay/conflict, old cancellation barrier, original approval/admission, administrator budget attribution and D1 proof/audit passed');
}
