import { test, expect } from '@playwright/test';

test('native bulk forms require review and recover an identical submitted operation', async ({ page, request }) => {
  await page.goto('/fixture-login');
  await expect(page.getByRole('heading', { name: 'Bulk invite', exact: true })).toBeVisible();
  await expect(page.getByText('Removing a repository collaborator can delete their private forks.', {exact:true})).toBeVisible();
  await page.getByLabel('Access lifetime (optional)').fill('1');
  await page.getByLabel('Handles and email addresses').fill('@alice\nalice\nmissing');
  await page.locator('input[name="repo_ids"][value="10"]').check();
  await page.locator('select[name="repo_grants"]').selectOption('10:push');
  await page.getByRole('button', { name: 'Resolve and review' }).press('Enter');
  await expect(page.getByText('Duplicate of row 1; no separate invitation')).toBeVisible();
  const policy=page.getByRole('region',{name:'Access expiry policy'});
  await expect(policy).toContainText('Remove eligible new access 1 hour after acceptance is confirmed');
  await expect(policy).toContainText('Upgrades and pre-existing access are excluded');
  await expect(policy).toContainText('Promoted organization owners');
  await expect(policy).toContainText('Email organization invitations have no access expiry');
  await expect(policy).toContainText('private forks');
  await expect(policy).toContainText('removes their team and repository access');
  await expect(page.locator('input[name="access_lifetime_hours"]')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Submit batch', exact: true })).toBeDisabled();
  let calls = (await (await request.get('/fixture-effects')).json()).calls;
  expect(calls.filter(([name]) => name === 'submit')).toEqual([]);
  await page.getByLabel('Remove row 3').check();
  await page.getByRole('button', { name: 'Apply review choices' }).press('Enter');
  await expect(page.getByText('Review revision 2.', { exact: false })).toBeVisible();
  await page.screenshot({ path: test.info().outputPath('bulk-review.png'), fullPage: true });
  await page.getByRole('button', { name: 'Submit batch', exact: true }).press('Enter');
  await expect(page.getByRole('heading', { name: 'Recover bulk operation' })).toBeVisible();
  await expect(page.getByRole('status')).toContainText('Submission may have been accepted');
  await page.getByRole('button', { name: 'Retry original operation' }).press('Enter');
  await expect(page.getByText('The batch was submitted.', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Submit batch', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Cancel unsent work' })).toBeVisible();
  calls = (await (await request.get('/fixture-effects')).json()).calls;
  const submitted = calls.filter(([name]) => name === 'submit').map(([, value]) => value);
  expect(submitted).toHaveLength(2);
  expect(submitted[0]).toEqual(submitted[1]);
  expect(submitted[0].submission.requests).toHaveLength(1);
  expect(submitted[0].submission.submitted_by).toBe(42);
  expect(submitted[0].submission.emails).toEqual([]);
  const created=calls.find(([name])=>name==='create')[1];
  expect(created.review.manifest.access_lifetime_seconds).toBe(3600);
  await expect(page.getByRole('region',{name:'Access expiry policy'})).toContainText('1 hour after acceptance is confirmed');
  await page.getByRole('button', { name: 'Cancel unsent work' }).press('Enter');
  await expect(page.getByRole('status').filter({ hasText: 'Cancellation was recorded' })).toBeVisible();
});
